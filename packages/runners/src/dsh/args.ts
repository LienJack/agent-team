import type { RunSpec } from '@agent-team/schema';

// `dsh --profile headless --patch <logDir>/dsh.patch.yml --json -` (spec §7 plus one overlay).
//
// Headless dsh picks its model from the profile's `agent-default-model` row, so the model is
// selected with a generated `--patch` overlay (written into the run's log dir, never the
// worktree). The overlay also sets approval `never` (an unattended worker must not wait for a
// prompt) and the sandbox mode: workspace-write for impl/fix runs, read-only for review runs.
// The permission-presets plugin requires the composed sandbox/approval to match a preset, so
// the overlay replaces the preset table with exactly one matching preset. With `endpoint`, the
// OpenRouter route (`llm-pi-ai` → `providers.openrouter`) goes to the server's key proxy on
// loopback and reads the run token from `apiKeyEnv` (docs/adr/0020): dsh 0.2.1-rc.5 sends every
// model request of that route to `POST {baseURL}/chat/completions`.

export const DSH_PATCH_FILE = 'dsh.patch.yml';
/** The dsh profile every run boots. */
export const DSH_PROFILE = 'headless';

/** Flags the runner needs (`--patch`/`--profile` from `dsh --help`, the rest from headless). */
export const DSH_REQUIRED_FLAGS = ['--profile', '--patch', '--json'] as const;
export const DSH_OPTIONAL_FLAGS = ['--session-id'] as const;

/** OpenRouter model ids are passed as-is; a leading `openrouter/` is dropped. */
export function dshModel(model: string): string {
  return model.startsWith('openrouter/') ? model.slice('openrouter/'.length) : model;
}

/** The run's own dsh state (sessions, storages) inside its log dir (docs/adr/0019). */
export const DSH_STATE_DIR = 'dsh-state';

/**
 * YAML overlay for one run. Values are JSON-quoted (valid YAML scalars, no injection). With
 * `stateDir`, dsh's session log and JSON storage go there instead of the shared `~/.dsh`, so the
 * sandbox can keep other sessions unreadable.
 */
export function dshPatch(
  spec: RunSpec,
  stateDir?: string,
  opts: { outerSandbox?: boolean; endpoint?: { baseUrl: string; apiKeyEnv: string } } = {},
): string {
  // Inside the Seatbelt wrapper (docs/adr/0019) dsh's own bash sandbox cannot start: macOS
  // refuses a nested `sandbox_apply` under any profile with a deny rule (measured 2026-11-21:
  // "sandbox_apply: Operation not permitted", every bash call failed). There the outer profile is
  // the confinement — reads and writes, read-only runs included — so dsh's own layer is off.
  const mode =
    opts.outerSandbox === true
      ? 'danger-full-access'
      : spec.writable
        ? 'workspace-write'
        : 'read-only';
  const q = (v: string) => JSON.stringify(v);
  return [
    '# Generated by @agent-team/runners for one run (runtime only).',
    '- id: agent-default-model',
    '  config:',
    `    provider: ${q('openrouter')}`,
    `    model: ${q(dshModel(spec.model))}`,
    ...(opts.endpoint === undefined
      ? []
      : [
          '- id: llm-pi-ai',
          '  config:',
          '    providers:',
          '      openrouter:',
          `        apiKeyEnv: ${q(opts.endpoint.apiKeyEnv)}`,
          `        baseURL: ${q(opts.endpoint.baseUrl)}`,
        ]),
    '- id: approval',
    '  config:',
    `    policy: ${q('never')}`,
    '- id: sandbox-policy',
    '  config:',
    `    mode: ${q(mode)}`,
    '- id: permission',
    '  config:',
    '    presets:',
    '      agent-team:',
    `        sandbox: ${q(mode)}`,
    `        approval: ${q('never')}`,
    `        name: ${q('agent-team')}`,
    `        description: ${q('agent-team worker (headless, never asks)')}`,
    `    defaultPreset: ${q('agent-team')}`,
    ...(stateDir === undefined
      ? []
      : [
          '- id: session-persistence-jsonl',
          '  config:',
          `    root: ${q(`${stateDir}/sessions`)}`,
          '- id: storage-json',
          '  config:',
          `    root: ${q(`${stateDir}/storages`)}`,
        ]),
    '',
  ].join('\n');
}

export function dshArgs(spec: RunSpec, patchPath: string, flags: ReadonlySet<string>): string[] {
  const args = ['--profile', DSH_PROFILE, '--patch', patchPath, '--json'];
  if (spec.resumeRef !== undefined && flags.has('--session-id')) {
    args.push('--session-id', spec.resumeRef);
  }
  args.push('-');
  return args;
}
