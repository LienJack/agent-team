import type { RunSpec } from '@agent-team/schema';

// `dsh --profile headless --patch <logDir>/dsh.patch.yml --json -` (spec §7 plus one overlay).
//
// Headless dsh picks its model from the profile's `agent-default-model` row, so the model is
// selected with a generated `--patch` overlay (written into the run's log dir, never the
// worktree). The overlay also sets approval `never` (an unattended worker must not wait for a
// prompt) and the sandbox mode: workspace-write for impl/fix runs, read-only for review runs.
// The permission-presets plugin requires the composed sandbox/approval to match a preset, so
// the overlay replaces the preset table with exactly one matching preset.

export const DSH_PATCH_FILE = 'dsh.patch.yml';

/** Flags the runner needs (`--patch`/`--profile` from `dsh --help`, the rest from headless). */
export const DSH_REQUIRED_FLAGS = ['--profile', '--patch', '--json'] as const;
export const DSH_OPTIONAL_FLAGS = ['--session-id'] as const;

/** OpenRouter model ids are passed as-is; a leading `openrouter/` is dropped. */
export function dshModel(model: string): string {
  return model.startsWith('openrouter/') ? model.slice('openrouter/'.length) : model;
}

/** YAML overlay for one run. Values are JSON-quoted (valid YAML scalars, no injection). */
export function dshPatch(spec: RunSpec): string {
  const mode = spec.writable ? 'workspace-write' : 'read-only';
  const q = (v: string) => JSON.stringify(v);
  return [
    '# Generated by @agent-team/runners for one run (runtime only).',
    '- id: agent-default-model',
    '  config:',
    `    provider: ${q('openrouter')}`,
    `    model: ${q(dshModel(spec.model))}`,
    '- id: approval',
    '  config:',
    `    policy: ${q('never')}`,
    '- id: sandbox-policy',
    '  config:',
    `    mode: ${q(mode)}`,
    '- id: permission',
    '  config:',
    '    presets:',
    '      agent-team:',
    `        sandbox: ${q(mode)}`,
    `        approval: ${q('never')}`,
    `        name: ${q('agent-team')}`,
    `        description: ${q('agent-team worker (headless, never asks)')}`,
    `    defaultPreset: ${q('agent-team')}`,
    '',
  ].join('\n');
}

export function dshArgs(spec: RunSpec, patchPath: string, flags: ReadonlySet<string>): string[] {
  const args = ['--profile', 'headless', '--patch', patchPath, '--json'];
  if (spec.resumeRef !== undefined && flags.has('--session-id')) {
    args.push('--session-id', spec.resumeRef);
  }
  args.push('-');
  return args;
}
