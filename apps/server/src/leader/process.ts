import { existsSync } from 'node:fs';
import { chmod, mkdir, rm, writeFile } from 'node:fs/promises';
import { delimiter, join } from 'node:path';
import { resolveRole, type QuotaState } from '@agent-team/core';
import {
  childEnv,
  probeClaudeCli,
  runClaudeText,
  type ClaudeProbe,
  type ClaudeTextResult,
} from '@agent-team/runners';
import { DATA_LAYOUT, type ModelsConfig } from '@agent-team/schema';
import { LEADER_OPTIONAL_FLAGS, LEADER_REQUIRED_FLAGS, leaderArgs } from './args.js';
import { LEADER_SYSTEM_PROMPT } from './prompt/system-v2.js';
import type { LeaderRuntime } from './types.js';

// Everything about the leader's `claude -p` processes: the working directory, the `team` shim
// that talks to the local listener as the leader actor, the child environment, the probe and one
// turn. The listener token stays in listener.json (read by the CLI); nothing secret is passed.

/** Non-secret claude variables passed through (its own config home); no API keys. */
const CLAUDE_ENV_NAMES = ['CLAUDE_CONFIG_DIR'];

export interface LeaderPaths {
  /** Empty working directory (sessions are stored per cwd, so it never changes). */
  cwd: string;
  /** Holds the `team` shim; first on the leader's PATH. */
  bin: string;
  /** Raw stream of the latest turn (events.jsonl, stderr.log, prompt.md). */
  turnLog: string;
}

export function leaderPaths(dataDir: string): LeaderPaths {
  const root = join(dataDir, 'leader');
  return { cwd: join(root, 'cwd'), bin: join(root, 'bin'), turnLog: join(root, 'turn') };
}

const shQuote = (value: string) => `'${value.replace(/'/g, `'\\''`)}'`;

/** Subcommands the leader may not run: they never end (`watch`, `serve`) or loop (`ask`). */
export const SHIM_REFUSED_COMMANDS = ['serve', 'watch', 'ask'] as const;

/**
 * `team` for the leader: this repo's CLI, the service's DATA directory and the leader's own
 * listener file (`DATA/leader/listener.json`, the leader-scoped token: the server treats every
 * call made with it as the leader actor; docs/adr/0014). The CLI runs with this machine's
 * permissions, so what would read a local file (`--ticket-file`) or never return (`serve` would
 * also recover the live database) is refused before node starts.
 */
export function teamShim(dataDir: string, nodePath: string, teamEntry: string): string {
  return [
    '#!/bin/sh',
    '# agent-team leader: `team` as the leader actor (generated by the server; do not edit)',
    "cmd=''",
    'for arg in "$@"; do',
    '  case "$arg" in',
    '    --ticket-file|--ticket-file=*)',
    '      echo "error: --ticket-file is not available to the leader" >&2',
    `      echo "hint: give the ticket on stdin: team task add ... - <<'EOF'" >&2`,
    '      exit 2 ;;',
    '    -*) ;;',
    '    *) if [ -z "$cmd" ]; then cmd="$arg"; fi ;;',
    '  esac',
    'done',
    'case "$cmd" in',
    `  ${SHIM_REFUSED_COMMANDS.join('|')})`,
    '    echo "error: team $cmd is not available to the leader" >&2',
    '    exit 2 ;;',
    'esac',
    `AGENT_TEAM_HOME=${shQuote(dataDir)} AGENT_TEAM_LISTENER_FILE=${shQuote(join(dataDir, DATA_LAYOUT.leaderListener))} exec ${shQuote(nodePath)} ${shQuote(teamEntry)} "$@"`,
    '',
  ].join('\n');
}

export interface ModelChoice {
  alias: string;
  model: string;
  effort?: string;
}

/**
 * The model of role `leader` (quota rules applied). The leader is a Claude conversation, so a
 * non-claude pick falls through to the first claude alias of the role.
 */
export function leaderModel(
  models: ModelsConfig,
  quota: QuotaState,
  now: Date,
): ModelChoice | undefined {
  const pick = (alias: string): ModelChoice | undefined => {
    const entry = models.models[alias];
    if (!entry || entry.runner !== 'claude') return undefined;
    return { alias, model: entry.model, ...(entry.effort ? { effort: entry.effort } : {}) };
  };
  const resolved = resolveRole('leader', quota, { models, now });
  if (resolved.ok) {
    const choice = pick(resolved.alias);
    if (choice) return choice;
  }
  const role = models.roles['leader'];
  for (const alias of role ? [role.use, ...role.fallback] : []) {
    const choice = pick(alias);
    if (choice) return choice;
  }
  return undefined;
}

export interface TurnInput {
  prompt: string;
  sessionId: string;
  resume: boolean;
  model: ModelChoice;
  timeoutMs: number;
  signal: AbortSignal;
}

/** Spawns the leader's claude processes; one instance per leader. */
export class LeaderProcess {
  private probed: ClaudeProbe | undefined;
  readonly paths: LeaderPaths;

  constructor(
    private readonly runtime: LeaderRuntime,
    private readonly dataDir: string,
  ) {
    this.paths = leaderPaths(dataDir);
  }

  private env(): Record<string, string> {
    const source = this.runtime.sourceEnv ?? process.env;
    const base = childEnv(CLAUDE_ENV_NAMES, {}, source);
    return { ...base, PATH: [this.paths.bin, base.PATH].join(delimiter) };
  }

  get flags(): ReadonlySet<string> {
    return this.probed?.flags ?? new Set();
  }

  /** Directories, the `team` shim and the CLI probe. Returns why it cannot run, if so. */
  async prepare(): Promise<{ problem?: string; loggedIn?: boolean }> {
    const entry = this.runtime.teamEntry;
    if (entry === undefined || !existsSync(entry)) {
      return {
        problem: `the team CLI is missing (${entry ?? 'no entry'}); run \`pnpm build\` first`,
      };
    }
    await mkdir(this.paths.cwd, { recursive: true, mode: 0o700 });
    await mkdir(this.paths.bin, { recursive: true, mode: 0o700 });
    const shim = join(this.paths.bin, 'team');
    await writeFile(
      shim,
      teamShim(this.dataDir, this.runtime.nodePath ?? process.execPath, entry),
      {
        mode: 0o700,
      },
    );
    await chmod(shim, 0o700);
    this.probed = await probeClaudeCli({
      ...(this.runtime.command ? { command: this.runtime.command } : {}),
      env: this.env(),
      cwd: this.paths.cwd,
      wanted: [...LEADER_REQUIRED_FLAGS, ...LEADER_OPTIONAL_FLAGS],
      required: LEADER_REQUIRED_FLAGS,
    });
    if (!this.probed.available) return { problem: this.probed.problems.join('; ') };
    return this.probed.loggedIn === undefined ? {} : { loggedIn: this.probed.loggedIn };
  }

  async turn(input: TurnInput): Promise<ClaudeTextResult> {
    const probe = this.probed;
    if (!probe?.available || probe.executable === undefined) {
      return {
        started: false,
        commands: [],
        denied: [],
        error: { kind: 'crash', message: 'claude was not probed' },
      };
    }
    const prefix =
      this.runtime.command && this.runtime.command.length > 0 ? this.runtime.command : [];
    const args = leaderArgs({
      model: input.model.model,
      effort: input.model.effort,
      sessionId: input.sessionId,
      resume: input.resume,
      systemPrompt: LEADER_SYSTEM_PROMPT,
      flags: probe.flags,
    });
    await rm(this.paths.turnLog, { recursive: true, force: true });
    return runClaudeText({
      command: probe.executable,
      args: [...prefix.slice(1), ...args],
      cwd: this.paths.cwd,
      env: this.env(),
      prompt: input.prompt,
      timeoutMs: input.timeoutMs,
      signal: input.signal,
      logDir: this.paths.turnLog,
    });
  }
}
